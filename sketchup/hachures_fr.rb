    def self.francais(nom, desc)
      t = FR[nom.to_s.upcase] || FR[nom.to_s]
      return t if t
      d = desc.to_s
      return d if d.empty? || d =~ /[éèàùç]/i
      mots = d.split(/(\W+)/).map { |w| MOTS.key?(w.downcase) ? MOTS[w.downcase] : w }
      r = mots.join.gsub(/\s+/, ' ').strip
      r = r.downcase if d == d.upcase && d =~ /[A-Z]/
      r.sub(/\A\p{L}/) { |c| c.upcase }
    end
